type Category = { id: string; name: string };
type Tag = { id: string; name: string };
type Provenance = {
  address: string | null;
  city: string | null;
  state: string | null;
  sourceUrl: string;
};
type PanelKind = null | "categorize" | "tags" | "comments" | "ai-edit";

export function ArtifactCard({
  artifact,
  boardId,
  signedImageUrl,
  categories,
  memberCategoryIds,
  tags,
  allTags,
  provenance,
  canEdit,
}: {
  artifact: Artifact;
  boardId: string;
  signedImageUrl?: string;
  categories: Category[];
  memberCategoryIds: string[];
  tags: Tag[];
  allTags: Tag[];
  provenance?: Provenance;
  canEdit: boolean;
}) {
  const [openPanel, setOpenPanel] = useState<PanelKind>(null);
  const formRef = useRef<HTMLFormElement>(null);

  return (
    <div className="group relative">
      {/* Hidden form for the Remove action */}
      {canEdit && (
        <form
          ref={formRef}
          action={deleteArtifact}
          className="hidden"
          aria-hidden="true"
        >
          <input type="hidden" name="id" value={artifact.id} />
          <input type="hidden" name="boardId" value={boardId} />
        </form>
      )}

      {canEdit && (
        <CardOverflowMenu
          kind={artifact.kind}
          onOpenPanel={setOpenPanel}
          onRemove={() => formRef.current?.requestSubmit()}
        />
      )}

      <CardBody
        artifact={artifact}
        signedImageUrl={signedImageUrl}
        provenance={provenance}
      />

      {tags.length > 0 && <TagsRow tags={tags} />}

      {openPanel && (
        <CardPanelDialog
          openPanel={openPanel}
          onClose={() => setOpenPanel(null)}
          artifact={artifact}
          boardId={boardId}
          categories={categories}
          memberCategoryIds={memberCategoryIds}
          tags={tags}
          allTags={allTags}
        />
      )}
    </div>
  );
}

