type ZoomAction = {
  label: string;
  onClick: () => void;
  variant?: "primary" | "danger" | "ghost";
  disabled?: boolean;
};

function ImageZoomDialog({
  src,
  alt,
  caption,
  onClose,
  actions,
}: {
  src: string;
  alt: string;
  caption?: string;
  onClose: () => void;
  /**
   * Optional action buttons. When provided, replaces the click-to-close
   * behavior on the image (so the user can't accidentally dismiss a
   * generated edit) — the explicit action buttons are the only way out
   * besides Esc / backdrop / X.
   */
  actions?: ZoomAction[];
}) {
  const ref = useRef<HTMLDialogElement>(null);

  useEffect(() => {
    const dlg = ref.current;
    if (!dlg) return;
    if (!dlg.open) dlg.showModal();
    return () => {
      if (dlg.open) dlg.close();
    };
  }, []);

  const hasActions = !!actions && actions.length > 0;

  return (
    <dialog
      ref={ref}
      onClose={onClose}
      onClick={(e) => {
        if (e.target === ref.current) onClose();
      }}
      onPointerDown={(e) => e.stopPropagation()}
      onPointerMove={(e) => e.stopPropagation()}
      onPointerUp={(e) => e.stopPropagation()}
      className="m-0 mx-auto my-auto max-h-[95dvh] max-w-[95vw] rounded-xl border-0 bg-transparent p-0 backdrop:bg-stone-900/80 backdrop:backdrop-blur-sm"
    >
      <div className="flex flex-col items-center gap-3">
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={src}
          alt={alt}
          onClick={hasActions ? undefined : onClose}
          className={`block max-h-[80dvh] w-auto max-w-[95vw] rounded-xl object-contain shadow-2xl ${
            hasActions ? "" : "cursor-zoom-out"
          }`}
          draggable={false}
        />
        {caption && (
          <figcaption
            style={{ fontFamily: SERIF }}
            className="max-w-[80vw] px-2 text-center text-sm italic leading-snug text-stone-100"
          >
            {caption}
          </figcaption>
        )}
        {hasActions && (
          <div className="mt-1 flex flex-wrap items-center justify-center gap-2">
            {actions!.map((a) => (
              <button
                key={a.label}
                type="button"
                onClick={a.onClick}
                disabled={a.disabled}
                className={zoomActionClass(a.variant)}
                style={{ letterSpacing: "0.12em" }}
              >
                {a.label}
              </button>
            ))}
          </div>
        )}
        <button
          type="button"
          onClick={onClose}
          aria-label="Close"
          className="absolute right-3 top-3 inline-flex h-8 w-8 items-center justify-center rounded-full bg-white/10 text-white backdrop-blur-sm hover:bg-white/20"
        >
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
            <path d="M6 6 L18 18 M18 6 L6 18" />
          </svg>
        </button>
      </div>
    </dialog>
  );
}

function zoomActionClass(variant: ZoomAction["variant"]): string {
  const base =
    "rounded-md px-4 py-2 text-xs uppercase disabled:opacity-50 transition-colors";
  switch (variant) {
    case "primary":
      return `${base} bg-stone-50 text-stone-900 hover:bg-white`;
    case "danger":
      return `${base} bg-red-600/90 text-white hover:bg-red-600`;
    default:
      return `${base} bg-white/10 text-white hover:bg-white/20`;
  }
}

const editImageInitial: EditImageState = { status: "idle" };
const remixImageInitial: RemixImageState = { status: "idle" };

function AiEditPanel({
  artifactId,
  boardId,
  onDone,
}: {
  artifactId: string;
  boardId: string;
  onDone: () => void;
}) {
  const [quota, setQuota] = useState<AiQuotaStatus | null>(null);
  const [variants, setVariants] = useState(1);
  const [reviewDismissed, setReviewDismissed] = useState(false);
  const [discarding, setDiscarding] = useState(false);
  const [editState, editAction, editPending] = useActionState(
    editImageArtifact,
    editImageInitial,
  );
  const [remixState, remixAction, remixPending] = useActionState(
    remixImageArtifact,
    remixImageInitial,
  );

  useEffect(() => {
    let cancelled = false;
    getAiQuota().then((q) => {
      if (!cancelled) setQuota(q);
    });
    return () => {
      cancelled = true;
    };
  }, []);

  const isRemix = variants > 1;
  const action = isRemix ? remixAction : editAction;
  const pending = isRemix ? remixPending : editPending;

  // Reviews — only one can be active at a time (the other path's state
  // sticks around but we hide it).
  const showingEditReview =
    !isRemix &&
    editState.status === "done" &&
    !reviewDismissed &&
    !!editState.signedUrl;
  const showingRemixReview =
    isRemix && remixState.status === "done" && !reviewDismissed;

  const errorMessage =
    editState.status === "error"
      ? editState.message
      : remixState.status === "error"
        ? remixState.message
        : null;

  const remainingNumber = quota?.exempt
    ? null
    : quota
      ? Math.max(0, quota.remaining ?? 0)
      : null;
  const remainingDisplay = quota?.exempt
    ? "∞"
    : quota
      ? Math.max(0, quota.remaining ?? 0).toString()
      : "…";
  const atLimit =
    !!quota && !quota.exempt && (quota.remaining ?? 0) <= 0;
  const remixWouldOverrun =
    !!quota && !quota.exempt && variants > (quota.remaining ?? 0);

  async function refreshQuota() {
    const q = await getAiQuota();
    setQuota(q);
  }

  async function handleDiscard() {
    if (editState.status !== "done") return;
    setDiscarding(true);
    try {
      await discardAiEdit({
        boardId,
        outputArtifactId: editState.outputArtifactId,
      });
      await refreshQuota();
      setReviewDismissed(true);
    } finally {
      setDiscarding(false);
    }
  }

  async function handleRemixConfirm(keepIds: string[]) {
    if (remixState.status !== "done") return;
    const allIds = remixState.results.map((r) => r.outputArtifactId);
    const keepSet = new Set(keepIds);
    const discard = allIds.filter((id) => !keepSet.has(id));
    setDiscarding(true);
    try {
      await keepRemixSelections({
        boardId,
        keepArtifactIds: keepIds,
        discardArtifactIds: discard,
      });
      await refreshQuota();
      setReviewDismissed(true);
      onDone();
    } finally {
      setDiscarding(false);
    }
  }

  const lastPrompt =
    isRemix && remixState.status === "done"
      ? remixState.prompt
      : editState.status === "done"
        ? editState.prompt
        : undefined;

  return (
    <>
      <form action={action} className="flex flex-col gap-3">
        <input type="hidden" name="boardId" value={boardId} />
        <input type="hidden" name="artifactId" value={artifactId} />
        <input type="hidden" name="variants" value={variants} />

        <p className="text-[11px] uppercase tracking-wide text-stone-500">
          {remainingDisplay} of {quota?.limit ?? "10"}{" "}
          {quota?.exempt ? "edits" : "edits left this week"}
        </p>

        <textarea
          name="prompt"
          rows={3}
          maxLength={1000}
          required
          placeholder={
            isRemix
              ? "e.g. Different cabinet colors — white, navy, walnut"
              : "e.g. Add a small pool with a tanning ledge to the backyard"
          }
          disabled={pending || atLimit}
          defaultValue={lastPrompt}
          className="w-full rounded-lg border border-stone-200 bg-white px-3 py-2 text-sm text-stone-900 placeholder:text-stone-400 focus:border-stone-400 focus:outline-none focus:ring-2 focus:ring-stone-200 disabled:bg-stone-50"
        />

        <div className="flex flex-wrap items-center gap-2">
          <span className="text-[10px] uppercase tracking-wider text-stone-500">
            Variants
          </span>
          <div className="inline-flex gap-1 rounded-full border border-stone-200 bg-white p-0.5">
            {[1, 2, 3, 4].map((n) => {
              const blocked =
                !!quota &&
                !quota.exempt &&
                remainingNumber !== null &&
                n > remainingNumber;
              return (
                <button
                  key={n}
                  type="button"
                  onClick={() => setVariants(n)}
                  aria-pressed={variants === n}
                  disabled={pending || blocked}
                  title={
                    blocked
                      ? `Only ${remainingNumber} edit${remainingNumber === 1 ? "" : "s"} left this week`
                      : undefined
                  }
                  className={`rounded-full px-2.5 py-1 text-xs transition-colors ${
                    variants === n
                      ? "bg-stone-900 text-stone-50"
                      : "text-stone-500 hover:text-stone-900 disabled:opacity-30"
                  }`}
                >
                  {n}
                </button>
              );
            })}
          </div>
          <span className="text-[11px] text-stone-500">
            {variants === 1
              ? "single edit"
              : `remix — ${variants} variants, uses ${variants} of your quota`}
          </span>
        </div>

        {errorMessage && (
          <p className="text-sm text-red-700">{errorMessage}</p>
        )}
        {atLimit && !errorMessage && (
          <p className="text-sm text-amber-700">
            You&apos;ve used your weekly AI edit quota. The counter resets on a
            rolling 7-day window.
          </p>
        )}

        <div className="flex items-center justify-end gap-2">
          <button
            type="submit"
            disabled={pending || atLimit || remixWouldOverrun}
            className="rounded-md bg-stone-900 px-3 py-1.5 text-xs uppercase tracking-wider text-stone-50 disabled:opacity-50"
            style={{ letterSpacing: "0.12em" }}
          >
            {pending
              ? isRemix
                ? `Generating ${variants}…`
                : "Editing…"
              : isRemix
                ? `Generate ${variants}`
                : "Generate"}
          </button>
        </div>
      </form>

      {showingEditReview && editState.status === "done" && editState.signedUrl && (
        <ImageZoomDialog
          src={editState.signedUrl}
          alt="AI edit preview"
          caption={editState.prompt}
          onClose={() => setReviewDismissed(true)}
          actions={[
            {
              label: discarding ? "Discarding…" : "Discard & retry",
              variant: "danger",
              onClick: handleDiscard,
              disabled: discarding,
            },
            {
              label: "Keep",
              variant: "primary",
              onClick: onDone,
              disabled: discarding,
            },
          ]}
        />
      )}

      {showingRemixReview && remixState.status === "done" && (
        <RemixGalleryDialog
          variants={remixState.results}
          requested={remixState.requested}
          failed={remixState.failed}
          prompt={remixState.prompt}
          pending={discarding}
          onClose={() => setReviewDismissed(true)}
          onConfirm={handleRemixConfirm}
          onDiscardAll={() => handleRemixConfirm([])}
        />
      )}
    </>
  );
}

function RemixGalleryDialog({
  variants,
  requested,
  failed,
  prompt,
  pending,
  onClose,
  onConfirm,
  onDiscardAll,
}: {
  variants: RemixVariant[];
  requested: number;
  failed: number;
  prompt: string;
  pending: boolean;
  onClose: () => void;
  onConfirm: (keepArtifactIds: string[]) => void;
  onDiscardAll: () => void;
}) {
  const ref = useRef<HTMLDialogElement>(null);
  const [selected, setSelected] = useState<Record<string, boolean>>(() =>
    Object.fromEntries(variants.map((v) => [v.outputArtifactId, true])),
  );
  const [zoomedId, setZoomedId] = useState<string | null>(null);

  useEffect(() => {
    const dlg = ref.current;
    if (!dlg) return;
    if (!dlg.open) dlg.showModal();
    return () => {
      if (dlg.open) dlg.close();
    };
  }, []);

  const keepCount = Object.values(selected).filter(Boolean).length;
  const zoomed = zoomedId
    ? variants.find((v) => v.outputArtifactId === zoomedId)
    : null;
  const keepIds = variants
    .filter((v) => selected[v.outputArtifactId])
    .map((v) => v.outputArtifactId);

  return (
    <dialog
      ref={ref}
      onClose={onClose}
      onClick={(e) => {
        if (e.target === ref.current) onClose();
      }}
      onPointerDown={(e) => e.stopPropagation()}
      onPointerMove={(e) => e.stopPropagation()}
      onPointerUp={(e) => e.stopPropagation()}
      className="m-0 mx-auto my-auto max-h-[95dvh] w-[min(900px,95vw)] rounded-xl border-0 bg-stone-900 p-0 shadow-2xl backdrop:bg-stone-900/80 backdrop:backdrop-blur-sm"
    >
      <div className="flex flex-col gap-4 p-5 sm:p-6">
        <div className="flex flex-wrap items-baseline justify-between gap-2">
          <div>
            <p className="text-[10px] uppercase tracking-[0.18em] text-stone-400">
              Pick which to keep
            </p>
            <p
              style={{ fontFamily: SERIF }}
              className="mt-0.5 text-base italic leading-snug text-stone-100"
            >
              {prompt}
            </p>
          </div>
          <p className="text-[11px] uppercase tracking-wide text-stone-400">
            {keepCount} of {variants.length} selected
            {failed > 0 ? ` · ${failed} of ${requested} failed` : ""}
          </p>
        </div>

        <div className="grid grid-cols-2 gap-3 sm:grid-cols-3 md:grid-cols-4">
          {variants.map((v) => {
            const isOn = !!selected[v.outputArtifactId];
            return (
              <label
                key={v.outputArtifactId}
                // Hover scale gated to hover-capable pointers only — touch
                // devices don't have a stable :hover, and scaling on tap
                // would feel laggy. Mobile users get the magnifier button
                // (top-left) instead.
                className={`group relative cursor-pointer overflow-hidden rounded-lg border-2 transition-transform duration-200 [@media(hover:hover)]:hover:z-10 [@media(hover:hover)]:hover:scale-[1.35] ${
                  isOn
                    ? "border-stone-50 ring-2 ring-stone-300/50"
                    : "border-transparent opacity-50 hover:opacity-100"
                }`}
              >
                <input
                  type="checkbox"
                  className="sr-only"
                  checked={isOn}
                  onChange={(e) =>
                    setSelected((s) => ({
                      ...s,
                      [v.outputArtifactId]: e.target.checked,
                    }))
                  }
                />
                {v.signedUrl ? (
                  /* eslint-disable-next-line @next/next/no-img-element */
                  <img
                    src={v.signedUrl}
                    alt={`Variant ${v.variantIndex + 1}`}
                    loading="lazy"
                    className="block aspect-square w-full object-cover"
                    draggable={false}
                  />
                ) : (
                  <div className="aspect-square animate-pulse bg-stone-700" />
                )}
                {/* Magnifier button — opens a fullscreen zoom of just this
                    variant. Pointer events stop here so tapping it doesn't
                    toggle the surrounding label's checkbox. */}
                {v.signedUrl && (
                  <button
                    type="button"
                    aria-label={`Zoom variant ${v.variantIndex + 1}`}
                    onPointerDown={(e) => e.stopPropagation()}
                    onPointerUp={(e) => e.stopPropagation()}
                    onClick={(e) => {
                      e.preventDefault();
                      e.stopPropagation();
                      setZoomedId(v.outputArtifactId);
                    }}
                    className="absolute left-2 top-2 inline-flex h-7 w-7 items-center justify-center rounded-full bg-stone-900/70 text-stone-50 shadow-sm backdrop-blur-sm transition-colors hover:bg-stone-900/90"
                  >
                    <svg
                      width="14"
                      height="14"
                      viewBox="0 0 24 24"
                      fill="none"
                      stroke="currentColor"
                      strokeWidth="2"
                      strokeLinecap="round"
                      strokeLinejoin="round"
                      aria-hidden="true"
                    >
                      <circle cx="11" cy="11" r="7" />
                      <path d="m21 21-4.3-4.3" />
                      <path d="M11 8v6 M8 11h6" />
                    </svg>
                  </button>
                )}
                {isOn && (
                  <span className="absolute right-2 top-2 inline-flex h-6 w-6 items-center justify-center rounded-full bg-stone-50 text-[10px] font-bold text-stone-900">
                    ✓
                  </span>
                )}
              </label>
            );
          })}
        </div>

        {zoomed?.signedUrl && (
          <ImageZoomDialog
            src={zoomed.signedUrl}
            alt={`Variant ${zoomed.variantIndex + 1}`}
            caption={prompt}
            onClose={() => setZoomedId(null)}
          />
        )}

        <div className="flex flex-wrap items-center justify-between gap-2">
          <button
            type="button"
            onClick={onDiscardAll}
            disabled={pending}
            className="rounded-md bg-red-600/90 px-4 py-2 text-xs uppercase tracking-wider text-white hover:bg-red-600 disabled:opacity-50"
            style={{ letterSpacing: "0.12em" }}
          >
            Discard all
          </button>
          <button
            type="button"
            onClick={() => onConfirm(keepIds)}
            disabled={pending || keepCount === 0}
            className="rounded-md bg-stone-50 px-4 py-2 text-xs uppercase tracking-wider text-stone-900 hover:bg-white disabled:opacity-50"
            style={{ letterSpacing: "0.12em" }}
          >
            {pending
              ? "Saving…"
              : `Keep ${keepCount} ${keepCount === 1 ? "variant" : "variants"}`}
          </button>
        </div>

        <button
          type="button"
          onClick={onClose}
          aria-label="Close"
          className="absolute right-3 top-3 inline-flex h-8 w-8 items-center justify-center rounded-full bg-white/10 text-white backdrop-blur-sm hover:bg-white/20"
        >
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
            <path d="M6 6 L18 18 M18 6 L6 18" />
          </svg>
        </button>
      </div>
    </dialog>
  );
}
