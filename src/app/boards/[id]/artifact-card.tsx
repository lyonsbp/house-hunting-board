function CardBody({
  artifact,
  signedImageUrl,
  provenance,
}: {
  artifact: Artifact;
  signedImageUrl?: string;
  provenance?: Provenance;
}) {
  switch (artifact.kind) {
    case "image":
      return (
        <ImageBody
          artifact={artifact}
          signedImageUrl={signedImageUrl}
          provenance={provenance}
        />
      );
    case "link":
      return <LinkBody artifact={artifact} />;
    case "text":
      return <TextBody artifact={artifact} />;
    case "note":
      return <NoteBody artifact={artifact} />;
  }
}

function ImageBody({
  artifact,
  signedImageUrl,
  provenance,
}: {
  artifact: Extract<Artifact, { kind: "image" }>;
  signedImageUrl?: string;
  provenance?: Provenance;
}) {
  const provenanceLabel = provenance ? formatProvenance(provenance) : null;
  const [zoomed, setZoomed] = useState(false);
  const isAiEdited = !!artifact.aiEditOf;
  return (
    <figure>
      <div className="relative overflow-hidden rounded-xl bg-stone-100 shadow-[0_2px_24px_-10px_rgba(0,0,0,0.25)]">
        {signedImageUrl ? (
          <button
            type="button"
            onClick={() => setZoomed(true)}
            aria-label="Zoom image"
            className="block w-full cursor-zoom-in"
          >
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img
              src={signedImageUrl}
              alt={artifact.body || "Board image"}
              className="block h-auto w-full"
              loading="lazy"
              draggable={false}
            />
          </button>
        ) : (
          <div className="aspect-square animate-pulse" />
        )}
        {isAiEdited && <AiBadge />}
      </div>
      {zoomed && signedImageUrl && (
        <ImageZoomDialog
          src={signedImageUrl}
          alt={artifact.body || "Board image"}
          caption={artifact.body}
          onClose={() => setZoomed(false)}
        />
      )}
      {artifact.body && (
        <figcaption
          style={{ fontFamily: SERIF }}
          className="mt-3 px-1 text-[13px] italic leading-snug text-stone-500"
        >
          {artifact.body}
        </figcaption>
      )}
      {provenanceLabel && (
        <p
          className="mt-2 px-1 text-[10px] uppercase tracking-[0.18em] text-amber-700/80"
          style={{ letterSpacing: "0.18em" }}
        >
          <a
            href={provenance!.sourceUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="hover:text-amber-900"
          >
            from {provenanceLabel}
          </a>
        </p>
      )}
    </figure>
  );
}

function formatProvenance(p: Provenance): string {
  const street = p.address?.trim();
  const cityState = [p.city, p.state].filter(Boolean).join(", ");
  if (street && cityState) return `${street}, ${cityState}`;
  if (street) return street;
  if (cityState) return cityState;
  try {
    return new URL(p.sourceUrl).host.replace(/^www\./, "");
  } catch {
    return "listing";
  }
}

