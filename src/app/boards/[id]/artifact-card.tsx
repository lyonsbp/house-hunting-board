function tiltFor(id: string): string {
  const hash = id
    .split("")
    .reduce((acc, ch) => (acc * 31 + ch.charCodeAt(0)) >>> 0, 0);
  const buckets = [-1.4, -0.8, -0.3, 0.3, 0.8, 1.4];
  return `${buckets[hash % buckets.length]}deg`;
}

